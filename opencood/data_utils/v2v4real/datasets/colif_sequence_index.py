"""Causal scene/source index for CoLIF V2V4Real sequences.

This module deliberately does not inherit the legacy V2V4Real datasets.  In
particular, a receiver timeline is defined by that receiver's own frames;
missing source frames remain missing instead of shortening the receiver
sequence to a cross-CAV intersection.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, Optional, Sequence, Tuple


_IGNORED_YAML_MARKERS = ("additional", "camera_gt")


@dataclass(frozen=True)
class SourceFrameRecord:
    """Paths and synthetic-clock metadata for one source capture."""

    scene_id: str
    source_id: str
    frame_key: str
    frame_index: int
    capture_time_s: float
    yaml_path: Path
    lidar_path: Path


class SceneSequenceIndex:
    """Index source-native frames without loading labels or point clouds.

    Parameters
    ----------
    root_dir
        A V2V4Real split directory whose children are scene directories.
    frame_period_s
        Synthetic frame period.  V2V4Real filenames do not provide a
        calibrated wall clock, so this value must be recorded in experiment
        provenance.
    split_manifest, split_name
        Optional disjoint-split manifest generated by
        ``opencood.tools.colif.build_split_manifest``.  When supplied, only
        entries assigned to ``split_name`` and originating from ``root_dir``
        are indexed.
    """

    def __init__(
        self,
        root_dir: str,
        frame_period_s: float = 0.1,
        split_manifest: Optional[str] = None,
        split_name: Optional[str] = None,
    ) -> None:
        self.root_dir = Path(root_dir).expanduser().resolve()
        self.frame_period_s = float(frame_period_s)
        if self.frame_period_s <= 0:
            raise ValueError("frame_period_s must be positive")
        if not self.root_dir.is_dir():
            raise FileNotFoundError("V2V4Real root does not exist: %s" % self.root_dir)

        allowed_scenes = self._load_allowed_scenes(split_manifest, split_name)
        self._records: Dict[str, Dict[str, Dict[str, SourceFrameRecord]]] = {}
        self._frame_keys: Dict[str, Dict[str, Tuple[str, ...]]] = {}
        self._incomplete_files: List[Tuple[str, str, str, str]] = []
        self._build(allowed_scenes)

        if not self._records:
            raise ValueError("No complete V2V4Real scenes found under %s" % self.root_dir)

    def _load_allowed_scenes(
        self, split_manifest: Optional[str], split_name: Optional[str]
    ) -> Optional[set]:
        if split_manifest is None:
            if split_name is not None:
                raise ValueError("split_name requires split_manifest")
            return None
        if split_name is None:
            raise ValueError("split_manifest requires split_name")

        manifest_path = Path(split_manifest).expanduser().resolve()
        with manifest_path.open("r", encoding="utf-8") as stream:
            manifest = json.load(stream)
        try:
            entries = manifest["splits"][split_name]
        except KeyError as exc:
            raise KeyError("Split %r is absent from %s" % (split_name, manifest_path)) from exc

        allowed = set()
        for entry in entries:
            if isinstance(entry, str):
                allowed.add(entry)
                continue
            if not isinstance(entry, Mapping) or "scene_id" not in entry:
                raise ValueError("Invalid split entry: %r" % (entry,))
            source_root = entry.get("source_root")
            if source_root is not None:
                entry_root = Path(source_root).expanduser().resolve()
                if entry_root != self.root_dir:
                    continue
            allowed.add(str(entry["scene_id"]))
        return allowed

    @staticmethod
    def _is_frame_yaml(path: Path) -> bool:
        return path.suffix == ".yaml" and not any(
            marker in path.name for marker in _IGNORED_YAML_MARKERS
        )

    @staticmethod
    def _clock_indices(frame_keys: Iterable[str]) -> Dict[str, int]:
        unique_keys = sorted(set(frame_keys))
        if not unique_keys:
            return {}
        try:
            numeric = {key: int(key) for key in unique_keys}
        except ValueError:
            return {key: index for index, key in enumerate(unique_keys)}
        origin = min(numeric.values())
        return {key: value - origin for key, value in numeric.items()}

    def _build(self, allowed_scenes: Optional[set]) -> None:
        scene_dirs = sorted(path for path in self.root_dir.iterdir() if path.is_dir())
        for scene_dir in scene_dirs:
            scene_id = scene_dir.name
            if allowed_scenes is not None and scene_id not in allowed_scenes:
                continue

            source_dirs = sorted(
                (path for path in scene_dir.iterdir() if path.is_dir()),
                key=lambda path: (int(path.name) if path.name.lstrip("-").isdigit() else 10**9,
                                  path.name),
            )
            raw_paths: Dict[str, Dict[str, Tuple[Path, Path]]] = {}
            all_keys: List[str] = []
            for source_dir in source_dirs:
                source_frames: Dict[str, Tuple[Path, Path]] = {}
                for yaml_path in sorted(source_dir.iterdir()):
                    if not self._is_frame_yaml(yaml_path):
                        continue
                    frame_key = yaml_path.stem
                    lidar_path = source_dir / (frame_key + ".pcd")
                    if not lidar_path.is_file():
                        self._incomplete_files.append(
                            (scene_id, source_dir.name, frame_key, "missing_lidar")
                        )
                        continue
                    source_frames[frame_key] = (yaml_path, lidar_path)
                    all_keys.append(frame_key)
                if source_frames:
                    raw_paths[source_dir.name] = source_frames

            clock_indices = self._clock_indices(all_keys)
            scene_records: Dict[str, Dict[str, SourceFrameRecord]] = {}
            scene_frame_keys: Dict[str, Tuple[str, ...]] = {}
            for source_id, source_frames in raw_paths.items():
                ordered_keys = tuple(sorted(source_frames))
                scene_frame_keys[source_id] = ordered_keys
                scene_records[source_id] = {
                    key: SourceFrameRecord(
                        scene_id=scene_id,
                        source_id=source_id,
                        frame_key=key,
                        frame_index=clock_indices[key],
                        capture_time_s=clock_indices[key] * self.frame_period_s,
                        yaml_path=source_frames[key][0],
                        lidar_path=source_frames[key][1],
                    )
                    for key in ordered_keys
                }
            if scene_records:
                self._records[scene_id] = scene_records
                self._frame_keys[scene_id] = scene_frame_keys

    def scene_ids(self) -> Tuple[str, ...]:
        return tuple(sorted(self._records))

    def source_ids(self, scene_id: str) -> Tuple[str, ...]:
        return tuple(self._records[scene_id].keys())

    def receiver_frame_keys(self, scene_id: str, receiver_id: str) -> Tuple[str, ...]:
        """Return the receiver's own timeline, never a source intersection."""

        return self._frame_keys[scene_id][str(receiver_id)]

    def source_record(
        self, scene_id: str, source_id: str, frame_key: str
    ) -> Optional[SourceFrameRecord]:
        return self._records[scene_id][str(source_id)].get(str(frame_key))

    def receiver_record(
        self, scene_id: str, receiver_id: str, frame_key: str
    ) -> SourceFrameRecord:
        record = self.source_record(scene_id, receiver_id, frame_key)
        if record is None:
            raise KeyError((scene_id, receiver_id, frame_key))
        return record

    def latest_arrived_source_record(
        self,
        scene_id: str,
        receiver_id: str,
        source_id: str,
        receiver_frame_key: str,
        delay_s: float,
    ) -> Optional[SourceFrameRecord]:
        """Select the newest source capture whose message has arrived.

        Arrival is causal: ``capture_time + delay <= receiver_time``.  A
        missing source frame yields an older record or ``None``; it never
        removes the receiver frame.
        """

        if delay_s < 0:
            raise ValueError("delay_s must be non-negative")
        receiver = self.receiver_record(scene_id, receiver_id, receiver_frame_key)
        latest = None
        for key in self._frame_keys[scene_id][str(source_id)]:
            candidate = self._records[scene_id][str(source_id)][key]
            arrival_time = candidate.capture_time_s + float(delay_s)
            if arrival_time <= receiver.capture_time_s + 1e-9:
                if latest is None or candidate.capture_time_s > latest.capture_time_s:
                    latest = candidate
        return latest

    @property
    def incomplete_files(self) -> Tuple[Tuple[str, str, str, str], ...]:
        return tuple(self._incomplete_files)

    def summary(self) -> dict:
        source_count = sum(len(sources) for sources in self._records.values())
        frame_count = sum(
            len(frames)
            for sources in self._records.values()
            for frames in sources.values()
        )
        return {
            "root_dir": str(self.root_dir),
            "clock_source": "synthetic_fixed_period",
            "frame_period_s": self.frame_period_s,
            "scene_count": len(self._records),
            "source_count": source_count,
            "complete_frame_count": frame_count,
            "incomplete_file_count": len(self._incomplete_files),
        }
